from pydantic import BaseModel, Field
from typing import Annotated, Literal
from operator import add


class AgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(..., description="List of messages exchanged with the agent")
    curated_questions: str = Field(..., description="Curated questions for the agent")
    prompt_query_context: str = Field(..., description="Detailed prompt with SQL DB context that will be used for the prompt query")
    is_safe : Literal["Yes", "No"] = Field(..., description="Indicates whether the agent is safe to use or not")
    generated_sql_query: str = Field(..., description="SQL query generated by the agent based on the prompt query context")
    sql_query_execution_results: str = Field(..., description="Results of the SQL query executed against the database")
    final_answer: str = Field(..., description="Final answer generated by the agent based on the SQL query execution results")
    
